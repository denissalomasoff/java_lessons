package org.java_lessons.lesson6.CookBook;

public class Cook {
    public static void isCooking(Object component) {
        if (component instanceof Chicken Chicken) {
            Chicken.chickCooking();
        }
        if (component instanceof Dorado Dorado) {
            Dorado.dorCooking();
        }
        if (component instanceof Duck Duck) {
            Duck.duckCooking();
        }
        if (component instanceof Salmon Salmon) {
            Salmon.salCooking();
        }
        if (component instanceof Sturgeon Sturgeon) {
            Sturgeon.sturCooking();
        }
        if (component instanceof Turkey Turkey) {
            Turkey.turCooking();
            ;
        }
    }

}
